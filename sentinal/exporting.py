"""Deterministic, atomic ``platforms/<platform>.toml`` exports.

SQLite is authoritative; these files are generated views of the watched-program
list for tooling that prefers TOML. Generation replaces only the marked generated
block, so anything a human wrote outside it survives regeneration — generated
files never overwrite manual settings, and the manual ``config.toml`` is never
written at all. Each file is swapped into place atomically and only when its
content actually changed, so identical state produces identical bytes.
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any, Iterable

from .store import Store

GENERATED_BEGIN = "# >>> generated by sentinal pro - edits outside this block are preserved >>>"
GENERATED_END = "# <<< generated by sentinal pro <<<"

#: Fixed key order for generated ``[[programs]]`` entries — determinism first.
_ENTRY_KEYS = ("id", "name", "url", "max_bounty", "priority", "lifecycle", "origin", "targets")


def export_platforms(store: Store, root: str | Path) -> dict[str, str]:
    """Write one ``<platform>.toml`` per platform. Returns ``{platform: outcome}``
    where outcome is ``"written"`` or ``"unchanged"``.

    Dismissed programs are retired from the export; active, paused and delisted
    programs stay visible (a delisting remains reviewable until dismissed).
    """
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    programs = store.list_programs(with_targets=True)
    by_platform: dict[str, list[dict[str, Any]]] = {}
    for program in programs:
        entries = by_platform.setdefault(str(program["platform"]), [])
        if program.get("lifecycle") != "dismissed":
            entries.append(program)
    for path in root.glob("*.toml"):
        if GENERATED_BEGIN in path.read_text(encoding="utf-8"):
            by_platform.setdefault(path.stem, [])
    outcomes: dict[str, str] = {}
    for platform in sorted(by_platform):
        path = root / f"{platform}.toml"
        generated = render_platform(by_platform[platform])
        outcomes[platform] = _write_preserving_manual(path, generated)
    return outcomes


def render_platform(programs: Iterable[dict[str, Any]]) -> str:
    rows = sorted(programs, key=lambda program: str(program.get("external_id") or program.get("id")))
    lines = [GENERATED_BEGIN, f"# {len(rows)} program(s); source of truth is the database", ""]
    for program in rows:
        lines.append("[[programs]]")
        for key in _ENTRY_KEYS:
            value = _entry_value(program, key)
            if value is None:
                continue
            lines.append(f"{key} = {_toml_value(value)}")
        lines.append("")
    lines.append(GENERATED_END)
    return "\n".join(lines) + "\n"


def _entry_value(program: dict[str, Any], key: str) -> Any:
    if key == "id":
        return str(program.get("external_id") or program.get("id"))
    if key == "targets":
        targets = sorted(
            f"{target['source_type']}:{target['target_key']}"
            for target in program.get("targets") or []
            if target.get("active")
        )
        return targets or None
    value = program.get(key)
    return value if value not in (None, "") else None


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    return json.dumps(str(value), ensure_ascii=False)


def _write_preserving_manual(path: Path, generated: str) -> str:
    existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    merged = _merge(existing, generated)
    if merged == existing:
        return "unchanged"
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", newline="\n", dir=path.parent,
        prefix=f".{path.name}.", suffix=".tmp", delete=False,
    ) as handle:
        temporary = Path(handle.name)
        handle.write(merged)
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    return "written"


def _merge(existing: str, generated: str) -> str:
    """Replace only the generated block of ``existing``; keep everything else.

    A pre-existing file without markers is preserved verbatim in front of the
    generated block (manual settings win, generation appends).
    """
    begin = existing.find(GENERATED_BEGIN)
    end = existing.find(GENERATED_END)
    if begin >= 0 and end > begin:
        head = existing[:begin]
        tail = existing[end + len(GENERATED_END) :].lstrip("\n")
        merged = head + generated
        if tail.strip():
            merged += tail if tail.endswith("\n") else tail + "\n"
        return merged
    if existing.strip():
        return existing.rstrip("\n") + "\n\n" + generated
    return generated
